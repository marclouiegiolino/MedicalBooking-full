// ── Startup Database Migration ────────────────────────────────────────────────
// Safely adds geo columns to hospital_information if they don't already exist.
// This is idempotent – safe to run every startup.
{
    await using var migScope = app.Services.CreateAsyncScope();
    var myCon = migScope.ServiceProvider.GetRequiredService<Medical.Api.Main.MyCon>();
    await using var migConn = myCon.GetConnection();
    await migConn.OpenAsync();

    // Read columns that already exist
    var existingCols = new System.Collections.Generic.HashSet<string>(StringComparer.OrdinalIgnoreCase);
    await using (var pragmaCmd = migConn.CreateCommand())
    {
        pragmaCmd.CommandText = "PRAGMA table_info(hospital_information)";
        await using var reader = await pragmaCmd.ExecuteReaderAsync();
        while (await reader.ReadAsync())
        {
            var colName = reader["name"]?.ToString();
            if (!string.IsNullOrEmpty(colName)) existingCols.Add(colName);
        }
    }

    var columnsToAdd = new (string name, string def)[]
    {
        ("latitude",       "REAL NOT NULL DEFAULT 0"),
        ("longitude",      "REAL NOT NULL DEFAULT 0"),
        ("service_radius", "REAL NOT NULL DEFAULT 0"),
    };

    foreach (var (colName, colDef) in columnsToAdd)
    {
        if (!existingCols.Contains(colName))
        {
            await using var alterCmd = migConn.CreateCommand();
            alterCmd.CommandText = $"ALTER TABLE hospital_information ADD COLUMN {colName} {colDef}";
            await alterCmd.ExecuteNonQueryAsync();
            app.Logger.LogInformation("Migration: added column '{Col}' to hospital_information", colName);
        }
    }
}
